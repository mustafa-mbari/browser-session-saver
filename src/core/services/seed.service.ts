import { newtabDB } from '@core/storage/newtab-storage';
import type { Board, BookmarkCategory, TodoList, QuickLink } from '@core/types/newtab.types';
import { SEED_TIMESTAMP } from '@core/constants/seed';

/**
 * Seeded records use fixed ids and an old timestamp. Seeding twice (two start tabs
 * opened at once, React StrictMode in development) writes the same records instead
 * of duplicates, and browsers sharing data get the same defaults rather than one
 * copy each. The old timestamp makes any real edit win over a fresh seed.
 */
export const SEED_IDS = {
  mainBoard: 'seed-board-main',
  bookmarksBoard: 'seed-board-bookmarks',
  privateCard: 'seed-card-private',
  workCard: 'seed-card-work',
  todoList: 'seed-todo-list',
  quickLinks: ['seed-ql-google', 'seed-ql-claude', 'seed-ql-translate'],
} as const;

/** Returns ISO string staggered by `offsetMs` from a base time. */
function ts(base: number, offsetMs: number): string {
  return new Date(base + offsetMs).toISOString();
}

interface SeedResult {
  mainBoard: Board;
  bookmarksBoard: Board;
  todoList: TodoList;
}

/**
 * Seeds the two default boards (Main + Bookmarks) and a default TodoList.
 * Should only be called when the DB has no boards yet.
 * Pass `{ skipSampleCards: true }` to create the boards without the demo
 * Private/Work cards.
 */
export async function seedDefaultData(
  options?: { skipSampleCards?: boolean },
): Promise<SeedResult> {
  const db = newtabDB;
  const base = Date.parse(SEED_TIMESTAMP);

  // ── Main board cards ──────────────────────────────────────────────────────

  const mainBoardId = SEED_IDS.mainBoard;

  const privateCard: BookmarkCategory = {
    id: SEED_IDS.privateCard,
    boardId: mainBoardId,
    name: 'Private',
    icon: '📁',
    color: '#6366f1',
    bookmarkIds: [],
    collapsed: false,
    colSpan: 3,
    rowSpan: 3,
    cardType: 'bookmark',
    createdAt: ts(base, 0),
    updatedAt: SEED_TIMESTAMP,
  };

  const workCard: BookmarkCategory = {
    id: SEED_IDS.workCard,
    boardId: mainBoardId,
    name: 'Work',
    icon: '💼',
    color: '#3b82f6',
    bookmarkIds: [],
    collapsed: false,
    colSpan: 3,
    rowSpan: 3,
    cardType: 'bookmark',
    createdAt: ts(base, 1),
    updatedAt: SEED_TIMESTAMP,
  };

  const mainCards = options?.skipSampleCards ? [] : [privateCard, workCard];

  const mainBoard: Board = {
    id: mainBoardId,
    name: 'Main',
    icon: '🏠',
    categoryIds: mainCards.map((c) => c.id),
    createdAt: ts(base, 0),
    updatedAt: SEED_TIMESTAMP,
  };

  // ── Default TodoList (for the TodoWidget in Focus / Minimal layouts) ───────

  const todoList: TodoList = {
    id: SEED_IDS.todoList,
    name: 'My Tasks',
    icon: '✅',
    position: 0,
    createdAt: ts(base, 0),
    updatedAt: SEED_TIMESTAMP,
  };

  // ── Bookmarks board (empty — user populates via Folder Explorer) ─────────

  const bookmarksBoardId = SEED_IDS.bookmarksBoard;

  const bookmarksBoard: Board = {
    id: bookmarksBoardId,
    name: 'Bookmarks',
    icon: '🔖',
    categoryIds: [],
    createdAt: ts(base, 1),
    updatedAt: SEED_TIMESTAMP,
  };

  // ── Default quick links ───────────────────────────────────────────────────

  const [googleId, claudeId, translateId] = SEED_IDS.quickLinks;
  const seedLink = { favIconUrl: '', isAutoGenerated: false, createdAt: SEED_TIMESTAMP, updatedAt: SEED_TIMESTAMP };
  const defaultQuickLinks: QuickLink[] = [
    { ...seedLink, id: googleId, title: 'Google', url: 'https://www.google.com', position: 0 },
    { ...seedLink, id: claudeId, title: 'Claude', url: 'https://claude.ai', position: 1 },
    { ...seedLink, id: translateId, title: 'Google Translate', url: 'https://translate.google.com', position: 2 },
  ];

  // ── Write everything to DB in one batch ───────────────────────────────────

  // Skip creating the default list if the user already has one.
  const existingLists = await db.getAll<TodoList>('todoLists');

  await Promise.all([
    db.put('boards', mainBoard),
    db.put('boards', bookmarksBoard),
    ...(existingLists.length === 0 ? [db.put('todoLists', todoList)] : []),
    ...mainCards.map((c) => db.put('bookmarkCategories', c)),
    ...defaultQuickLinks.map((l) => db.put('quickLinks', l)),
  ]);

  return { mainBoard, bookmarksBoard, todoList };
}
